"use client";

import { useEffect, useState } from "react";
import { useRouter } from "next/navigation";
import { Button } from "@/components/ui/Button";
import { Input } from "@/components/ui/Input";
import { createClient } from "@/lib/supabase/client";
import { signOut } from "../actions";

type Factor = { id: string; friendly_name?: string };
type Enrollment = { id: string; qr: string; secret: string };

export function MfaForm() {
  const router = useRouter();
  const [factors, setFactors] = useState<Factor[] | null>(null);
  const [factorId, setFactorId] = useState("");
  const [enrollment, setEnrollment] = useState<Enrollment | null>(null);
  const [code, setCode] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [attempt, setAttempt] = useState(0);
  const [hasPending, setHasPending] = useState(false);

  useEffect(() => {
    let active = true;
    createClient().auth.mfa.listFactors().then(({ data, error }) => {
      if (!active) return;
      if (error) { setError("Не удалось получить способы входа. Повторите попытку."); return; }
      const verified = data.totp.filter((factor) => factor.status === "verified");
      setFactors(verified);
      setHasPending(data.all.some((factor) => factor.factor_type === "totp" && factor.status === "unverified" && factor.friendly_name?.startsWith("Gamma Piu ")));
      setFactorId(verified[0]?.id ?? "");
      setError("");
    }).catch(() => { if (active) setError("Не удалось подключиться. Повторите попытку."); });
    return () => { active = false; };
  }, [attempt]);

  async function enroll() {
    if (busy) return;
    setBusy(true); setError("");
    try {
      const { data, error } = await createClient().auth.mfa.enroll({ factorType: "totp", friendlyName: `Gamma Piu ${new Date().toISOString()}` });
      if (error) throw error;
      setEnrollment({ id: data.id, qr: data.totp.qr_code, secret: data.totp.secret });
      setFactorId(data.id);
    } catch { setError("Не удалось настроить приложение. Повторите попытку или обратитесь к владельцу Supabase."); }
    finally { setBusy(false); }
  }

  async function verify(event: React.FormEvent) {
    event.preventDefault();
    if (busy || !factorId) return;
    setBusy(true); setError("");
    try {
      const { error } = await createClient().auth.mfa.challengeAndVerify({ factorId, code });
      if (error) throw error;
      // Invalidate the router cache so protected pages read the fresh AAL2 cookie.
      router.replace("/admin");
      router.refresh();
    } catch { setError("Код не подошёл или истёк. Введите новый шестизначный код."); setBusy(false); }
  }

  async function resetPending() {
    if (busy) return;
    setBusy(true); setError("");
    try {
      const db = createClient();
      const { data, error } = await db.auth.mfa.listFactors();
      if (error) throw error;
      // Only the user's explicitly abandoned setups from this application.
      // A verified factor is never removed by this screen.
      for (const factor of data.all.filter((item) => item.factor_type === "totp" && item.status === "unverified" && item.friendly_name?.startsWith("Gamma Piu "))) {
        const { error } = await db.auth.mfa.unenroll({ factorId: factor.id });
        if (error) throw error;
      }
      setHasPending(false);
    } catch { setError("Не удалось сбросить настройку. Повторите попытку."); }
    finally { setBusy(false); }
  }

  return (
    <>
      {error && <p role="alert" className="text-sm text-danger">{error}</p>}
      {factors === null ? (
        <div aria-live="polite">{error ? <Button onClick={() => setAttempt((n) => n + 1)}>Повторить</Button> : "Загрузка…"}</div>
      ) : !factorId ? (
        <>
          <p className="text-sm text-muted">Для управления магазином нужен код из приложения-аутентификатора. Сохраните его резервную копию в своём приложении.</p>
          <Button onClick={enroll} disabled={busy}>{busy ? "Подготовка…" : "Настроить приложение"}</Button>
          {hasPending && <div className="flex flex-col gap-2">
            <p className="text-xs text-muted">Есть незавершённая настройка. Её сброс отменит подключение, начатое в других вкладках. Уже подключённые приложения сохранятся.</p>
            <Button variant="secondary" onClick={resetPending} disabled={busy}>Сбросить незавершённую настройку</Button>
          </div>}
        </>
      ) : (
        <form onSubmit={verify} className="flex flex-col gap-4">
          {enrollment && <>
            <p className="text-sm text-muted">Отсканируйте QR-код приложением-аутентификатором. Затем введите код. Никому не передавайте QR-код и ключ.</p>
            {/* The QR is generated by Supabase Auth and must stay on this device. */}
            {/* eslint-disable-next-line @next/next/no-img-element */}
            <img src={enrollment.qr} width={240} height={240} alt="QR-код для приложения-аутентификатора" className="max-w-full self-center rounded-panel bg-white p-3" />
            <details className="text-sm"><summary className="cursor-pointer">Ключ для ручного ввода</summary><code className="mt-2 block break-all select-all">{enrollment.secret}</code></details>
          </>}
          {!enrollment && factors.length > 1 && <fieldset className="flex flex-col gap-2"><legend>Приложение</legend>{factors.map((factor, index) => <label key={factor.id} className="flex gap-2"><input type="radio" name="factor" value={factor.id} checked={factorId === factor.id} onChange={() => setFactorId(factor.id)} />{factor.friendly_name || `Приложение ${index + 1}`}</label>)}</fieldset>}
          <Input label="Код из приложения" value={code} onChange={(event) => setCode(event.target.value.replace(/\D/g, "").slice(0, 6))} inputMode="numeric" autoComplete="one-time-code" pattern="[0-9]{6}" maxLength={6} required />
          <Button type="submit" disabled={busy || code.length !== 6}>{busy ? "Проверка…" : "Подтвердить вход"}</Button>
        </form>
      )}
      <p className="text-xs text-muted">Если доступа к приложению нет, восстановите его из резервной копии или обратитесь к владельцу проекта Supabase. Вход только по паролю отключён.</p>
      <form action={signOut}><Button type="submit" variant="secondary" className="w-full">Выйти</Button></form>
    </>
  );
}
